#!/usr/bin/env python3
"""Summarise Phase 1 instrument outputs (tests_v41: PAUSE, PERSIST, LASR, STAGES) into a markdown baseline table.
usage: summarize_v41.py <dir with comboA_<block>/dev_*.json> [> BASELINES.md]
Descriptive only: mean, SD and a 95% t-interval per readout; paired contrasts where the design is paired. No grades."""
import glob, json, math, os, statistics as S, sys
T975 = {2: 12.71, 3: 4.30, 4: 3.18, 5: 2.78, 6: 2.57, 7: 2.45, 8: 2.36, 9: 2.31, 10: 2.26, 12: 2.20, 16: 2.13, 24: 2.07, 32: 2.04, 48: 2.01}
def tq(n): return T975.get(n) or T975[min(T975, key=lambda k: abs(k - n))]
def ci(x):
    x = [v for v in x if v is not None and v == v and math.isfinite(v)]; n = len(x)  # NaN is written to JSON as null
    if n < 2: return n, (x[0] if x else float("nan")), float("nan"), (float("nan"), float("nan"))
    m, sd = S.mean(x), S.stdev(x); h = tq(n) * sd / math.sqrt(n); return n, m, sd, (m - h, m + h)
def f(v): return "nan" if v != v else (f"{v:.3g}" if abs(v) < 1000 else f"{v:.0f}")
root = sys.argv[1]; out = [f"# Phase 1 instrument baselines (Combo A, dev seeds)", "",
 "Descriptive baselines from `tests_v41.ts` via `run_v41.ts`; generated by `specialists/tools/summarize_v41.py`. No grading claims.", ""]
for path in sorted(glob.glob(os.path.join(root, "*", "dev_*.json"))):
    j = json.load(open(path)); A = j["arms"]; e = j["energy"]
    out += [f"## {j['key']} — arm {j['arm']}, seeds {j['seeds'][0]}-{j['seeds'][-1]} (n={len(j['seeds'])})", "",
            f"Bundle {str(j.get('bundle'))[:12]}; {j['seconds']:.0f} s wall, {e['cpuSec']:.0f} CPU-s; {e['kJperOrgDay']:.1f} kJ and {e['cpuSecPerOrgDay']:.2f} CPU-s per organism-day; energy-ledger max error {e['ledgerMaxDaily']:.1e}, non-finite {e['ledgerNonFinite']}.", "",
            "| readout | n | mean | SD | 95% CI |", "|---|---|---|---|---|"]
    for k, v in A.items():
        n, m, sd, (lo, hi) = ci(v); out.append(f"| {k} | {n} | {f(m)} | {f(sd)} | [{f(lo)}, {f(hi)}] |")
    if j["key"] == "PAUSE":
        q0 = A["choice quality after gap 0"]; out += ["", "Paired idle-as-progress index = choice quality (gap 0) minus choice quality (gap G); > 0 means the idle gap cost choice quality.", "", "| gap G | n | mean index | 95% CI |", "|---|---|---|---|"]
        for G in (60, 240, 720):
            d = [a - b for a, b in zip(q0, A[f"choice quality after gap {G}"]) if a is not None and b is not None]; n, m, sd, (lo, hi) = ci(d); out.append(f"| {G} | {n} | {f(m)} | [{f(lo)}, {f(hi)}] |")
    if j["key"] == "LASR":
        out += ["", "Seeds whose prediction moved at all at +1 tick: " + ", ".join(f"{k.split(' shift')[0]} {sum(1 for x in v if x > 0)}/{len(v)}" for k, v in A.items() if "+1 (" in k)]
    if j["key"] == "STAGES":
        out += ["", "Paired stage contrasts (choice quality): S2 - S1 and S3 - S1.", ""]
        for a, b in (("S2", "S1"), ("S3", "S1"), ("S3", "S2")):
            d = [x - y for x, y in zip(A[f"{a} choice quality"], A[f"{b} choice quality"]) if x is not None and y is not None]; n, m, sd, (lo, hi) = ci(d); out.append(f"- {a} - {b}: mean {f(m)}, 95% CI [{f(lo)}, {f(hi)}] (n={n})")
    out.append("")
print("\n".join(out))
